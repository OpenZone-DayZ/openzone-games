# ---------------------------------------------------------------- a card
#
# A turned picture is cut to its own unturned box (measured 2026-11-25: the
# trump under the stock showed only as wide as it stood, the corners of the
# fanned cards were gone). So a card is a square frame CARD_BOX diagonals of
# the card wide, which the script turns (Widget.SetRotation, as the game's
# radial menu turns its layouts' roots); inside it lie the card's shadow, its
# glow (hidden until the script shows and tints it) and its face, every part a
# fraction of the frame. Every card of the table is 5 : 7.

CARD_BOX = 1.1


def card():
    d = CARD_BOX * math.hypot(5, 7)
    fw, fh = 5 / d, 7 / d
    fx, fy = (1 - fw) / 2, (1 - fh) / 2
    gm = 0.18 * fw                      # the glow: 18 units round a 100-wide card
    sm, sd = 0.08 * fw, 0.03 * fw       # the shadow: 8 units round it, 3 units down
    rm = 3 / 54 * fw                    # the ring: 3 units round a pocket's 54-wide card

    def f(x, y, w, h):
        return frac(round(x, 4), round(y, 4), round(w, 4), round(h, 4))

    kids = [
        image("OZG_CardShadow", f(fx - sm, fy - sm + sd, fw + 2 * sm, fh + 2 * sm), 0, "ozg_table_shadow_ca",
              "0 0 0 0.55"),
        image("OZG_CardGlow", f(fx - gm, fy - gm, fw + 2 * gm, fh + 2 * gm), 1, "ozg_table_glow_ca", "1 1 1 1",
              [("visible", 0)]),
        # The ring of a pocket's card picked for a swap (the mock-up's solid
        # 3-unit ring), shown and tinted by the script.
        image("OZG_CardRing", f(fx - rm, fy - rm, fw + 2 * rm, fh + 2 * rm), 2, "ozg_round_ring_ca", "1 1 1 1",
              [("visible", 0)]),
        image("OZG_CardFace", f(fx, fy, fw, fh), 3),
        # The marks (tools/make_marks.py), placed by the script in pixels
        # inside the frame, so that they turn with the card: on a back the
        # sign of a card read or noticed, and a read card's pencilled face; on
        # a face, in the same sign picture, a noticed card's speck.
        image("OZG_CardSign", exact(0, 0, 1, 1), 4, None, "1 1 1 1", [("visible", 0)]),
        image("OZG_CardPencil", exact(0, 0, 1, 1), 5, None, "1 1 1 1", [("visible", 0)]),
    ]
    return block("FrameWidgetClass", "OZG_Card",
                 [("ignorepointer", 1), ("clipchildren", 0)] + exact(0, 0, 100, 100) + [("priority", 1)], kids)


# ---------------------------------------------------------------- a seat's plate
#
# A button, so the host can pick a seat by its name. The plate is PLATE_PAD
# units inside the button on every side, for the ring that marks the seat the
# host picked; every part is a fraction of the button, so a crowded table can
# make the plates narrower (the text keeps its size).

PLATE_PAD = 4
PLATES = {"classic": (180, 48), "stalker": (190, 46)}


def inset(pw, ph, x, y, w, h):
    """A place given in units of the plate, as fractions of its button."""
    bw, bh = pw + 2 * PLATE_PAD, ph + 2 * PLATE_PAD
    return frac(round((x + PLATE_PAD) / bw, 4), round((y + PLATE_PAD) / bh, 4), round(w / bw, 4), round(h / bh, 4))



def rgb(hexcode, alpha=1.0):
    h = hexcode.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return "%.3f %.3f %.3f %.3g" % (r, g, b, alpha)


def block(kind, name, attrs, children=None, depth=0):
    pad = " " * depth
    lines = [pad + kind + " " + name + " {"]
    for key, value in attrs:
        if " " in key:
            key = '"' + key + '"'
        lines.append(pad + " " + key + " " + str(value))
    if children:
        lines.append(pad + " {")
        for kind_, name_, attrs_, kids_ in children:
            lines.append(block(kind_, name_, attrs_, kids_, depth + 2))
        lines.append(pad + " }")
    lines.append(pad + "}")
    return "\n".join(lines)


def exact(x, y, w, h):
    return [("position", "%s %s" % (x, y)), ("size", "%s %s" % (w, h)),
            ("hexactpos", 1), ("vexactpos", 1), ("hexactsize", 1), ("vexactsize", 1)]


def frac(x, y, w, h):
    return [("position", "%s %s" % (x, y)), ("size", "%s %s" % (w, h)),
            ("hexactpos", 0), ("vexactpos", 0), ("hexactsize", 0), ("vexactsize", 0)]


def fill():
    return frac(0, 0, 1, 1)


def panel(name, place, color, prio, extra=None):
    attrs = [("ignorepointer", 1)] + place + [("color", color), ("style", "rover_sim_colorable"), ("priority", prio)]
    return ("PanelWidgetClass", name, attrs + (extra or []), None)


def text(name, place, size, font, color, prio, halign="left", content="", extra=None):
    attrs = [("ignorepointer", 1), ("color", color)] + place + [
        ("text", '"%s"' % content), ("font", '"%s"' % font),
        ("exact text", 1), ("exact text size", size),
        ("text halign", halign), ("text valign", "center"), ("priority", prio)]
    return ("TextWidgetClass", name, attrs + (extra or []), None)


def image(name, place, prio, texture=None, color="1 1 1 1", extra=None):
    attrs = [("ignorepointer", 1), ("color", color)] + place + [("priority", prio)]
    if texture:
        attrs.append(("image0", '"%s%s.paa"' % (TEX, texture)))
    attrs += [("mode", "blend"), ("src alpha", 1), ("stretch mode", "stretch_w_h")]
    return ("ImageWidgetClass", name, attrs + (extra or []), None)


def frame(name, place, prio, kids=None, extra=None):
    # A container never takes the pointer: a frame over a button would answer
    # in its place (research's node cards, 2026-10-31). Buttons inside it do.
    attrs = [("ignorepointer", 1), ("clipchildren", 0)] + place + [("priority", prio)]
    return ("FrameWidgetClass", name, attrs + (extra or []), kids)


def button(name, place, prio, kids, visible=1, empty=False):
    # A button with no style paints a light box where nothing opaque covers it
    # (dayz-modding, gui-layouts §31); `style Empty` paints nothing at all.
    attrs = [("visible", visible)] + place + [("text", '""'), ("priority", prio)]
    if empty:
        attrs.append(("style", "Empty"))
    return ("ButtonWidgetClass", name, attrs, kids)



# Writes the game window's .layout files: the window, a card, a seat chip.
#
# Usage: python -I tools/make_layouts.py
#
# The window is many near-identical blocks (buttons, log lines), and a block
# typed twenty times drifts; here every block comes from one function. All
# numbers are layout units: 1 px at 1080 rows, H / 1080 px on a taller screen.
# What a script places itself (cards, chips, the stacked buttons) it places in
# real pixels, measured from the window it finds on screen.
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "OpenZone_Games", "gui", "layouts")
HEAD = "// GENERATED by tools/make_layouts.py -- edit the script, not this file.\n"

FONT_S = "gui/fonts/etelkatextpro16"
FONT_M = "gui/fonts/etelkatextpro22"
FONT_L = "gui/fonts/etelkatextpro28"

INK = "0.92 0.92 0.86 1"
DIM = "0.62 0.66 0.6 1"
WARM = "1 0.74 0.5 1"
GOLD = "0.95 0.8 0.35 1"


def block(kind, name, attrs, children=None, depth=0):
    pad = " " * depth
    lines = [pad + kind + " " + name + " {"]
    for key, value in attrs:
        if " " in key:
            key = '"' + key + '"'
        lines.append(pad + " " + key + " " + str(value))
    if children:
        lines.append(pad + " {")
        for child in children:
            lines.append(child_text(child, depth + 2))
        lines.append(pad + " }")
    lines.append(pad + "}")
    return "\n".join(lines)


def child_text(child, depth):
    kind, name, attrs, children = child
    return block(kind, name, attrs, children, depth)


def exact(x, y, w, h):
    return [("position", "%s %s" % (x, y)), ("size", "%s %s" % (w, h)),
            ("hexactpos", 1), ("vexactpos", 1), ("hexactsize", 1), ("vexactsize", 1)]


def fill():
    return [("position", "0 0"), ("size", "1 1"),
            ("hexactpos", 1), ("vexactpos", 1), ("hexactsize", 0), ("vexactsize", 0)]


def panel(name, place, color, extra=None):
    attrs = [("ignorepointer", 1)] + place + [("color", color), ("style", "rover_sim_colorable")]
    if extra:
        attrs += extra
    return ("PanelWidgetClass", name, attrs, None)


def text(name, place, size, font, color, halign="left", content="", extra=None):
    attrs = [("ignorepointer", 1), ("color", color)] + place + [
        ("text", '"%s"' % content), ("font", '"%s"' % font),
        ("exact text", 1), ("exact text size", size),
        ("text halign", halign), ("text valign", "center")]
    if extra:
        attrs += extra
    return ("TextWidgetClass", name, attrs, None)


def image(name, place, extra=None):
    attrs = [("ignorepointer", 1), ("color", "1 1 1 1")] + place + [
        ("mode", "blend"), ("src alpha", 1), ("stretch mode", "stretch_w_h")]
    if extra:
        attrs += extra
    return ("ImageWidgetClass", name, attrs, None)


def button(name, x, y, w, h, label, visible=1, tone="0.16 0.2 0.17 1", ink=INK, size=16):
    kids = [
        panel(name + "Edge", exact(-1, -1, w + 2, h + 2), "0.36 0.4 0.34 1", [("priority", 0)]),
        panel(name + "Bg", exact(0, 0, w, h), tone, [("priority", 1)]),
        text(name + "Text", exact(0, 0, w, h), size, FONT_S, ink, "center", label, [("priority", 2)]),
    ]
    attrs = [("visible", visible)] + exact(x, y, w, h) + [("text", '""'), ("priority", 5)]
    return ("ButtonWidgetClass", name, attrs, kids)


def write(name, body):
    path = os.path.join(OUT, name)
    with io.open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEAD + body + "\n")
    print("wrote", name, len(body), "chars")



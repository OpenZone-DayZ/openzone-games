def look_button(look, name, x, y, w, h, label, tone, prio, visible=0, size=None):
    """A button of a look: an edge, a ground, its label. Tone: moment, host, red.
    The classic look's buttons have round corners (white shapes of
    tools/make_table.py, tinted); the stalkers' are flat steel."""
    c = C[look]
    bg, edge, ink = c[tone + "_bg"], c[tone + "_edge"], c[tone + "_ink"]
    # Everything inside the button's own box: whether a button clips what
    # sticks out of it is not measured here.
    if look == "classic":
        font = ETELKA_M if tone == "moment" else ETELKA_S
        size = size or (17 if tone == "moment" else 15)
        if tone == "moment":
            kids = [
                image(name + "Bg", exact(0, 0, w, h), 0, "ozg_round_btn_ca", bg),
                image(name + "Edge", exact(0, 0, w, h), 1, "ozg_round_btn_edge_ca", edge),
            ]
        elif w <= 40:
            kids = [image(name + "Bg", exact(0, 0, w, h), 0, "ozg_round_close_ca", bg)]
        else:
            kids = [image(name + "Bg", exact(0, 0, w, h), 0, "ozg_round_wide_ca", bg)]
    else:
        font = OSWALD
        size = size or (21 if tone == "moment" else 19)
        kids = [
            panel(name + "Edge", exact(0, 0, w, h), edge, 0),
            panel(name + "Bg", exact(1, 1, w - 2, h - 2), bg, 1),
        ]
    kids.append(text(name + "Text", exact(0, 0, w, h), size, font, ink, 2, "center", label))
    return button(name, exact(x, y, w, h), prio, kids, visible, True)



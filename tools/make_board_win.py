def rgb(hexcode, alpha=1.0):
    h = hexcode.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return "%.3f %.3f %.3f %.3g" % (r, g, b, alpha)


def num(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


# ---------------------------------------------------------------- layout blocks

def block(kind, name, attrs, children=None, depth=0):
    pad = " " * depth
    lines = [pad + kind + " " + name + " {"]
    for key, value in attrs:
        if " " in key:
            key = '"' + key + '"'
        lines.append(pad + " " + key + " " + str(value))
    if children:
        lines.append(pad + " {")
        for kind_, name_, attrs_, kids_ in children:
            lines.append(block(kind_, name_, attrs_, kids_, depth + 2))
        lines.append(pad + " }")
    lines.append(pad + "}")
    return "\n".join(lines)


def exact(x, y, w, h):
    return [("position", "%s %s" % (num(x), num(y))), ("size", "%s %s" % (num(w), num(h))),
            ("hexactpos", 1), ("vexactpos", 1), ("hexactsize", 1), ("vexactsize", 1)]


def panel(name, place, color, prio=0, extra=None):
    attrs = [("ignorepointer", 1)] + place + [("color", color), ("style", "rover_sim_colorable"), ("priority", prio)]
    return ("PanelWidgetClass", name, attrs + (extra or []), None)


def image(name, place, prio, texture=None, color="1 1 1 1", extra=None):
    attrs = [("ignorepointer", 1), ("color", color)] + place + [("priority", prio)]
    if texture:
        attrs.append(("image0", '"%s%s.paa"' % (TEX, texture)))
    attrs += [("mode", "blend"), ("src alpha", 1), ("stretch mode", "stretch_w_h")]
    return ("ImageWidgetClass", name, attrs + (extra or []), None)


def frame(name, place, prio, kids=None, extra=None, clip=0):
    attrs = [("ignorepointer", 1), ("clipchildren", clip)] + place + [("priority", prio)]
    return ("FrameWidgetClass", name, attrs + (extra or []), kids)


def text(name, x, y, w, h, px, face, color, prio=5, halign="left", content="", extra=None):
    """A line of text where the canvas has it: `px` its CSS size, `face` s (regular), b
    (600/700) or p (the serif)."""
    size = int(round(px * K_TEXT[face]))
    if face == "s":
        font = ETELKA_L if size > 19 else ETELKA
    elif face == "b":
        font = BOLD
    else:
        font = SERIF_L if size > 22 else SERIF
    attrs = [("ignorepointer", 1)] + exact(x, y, w, h) + [
        ("color", rgb(color)), ("text", '"%s"' % content), ("font", '"%s"' % font),
        ("exact text", 1), ("exact text size", size),
        ("text halign", halign), ("text valign", "center"), ("priority", prio)]
    return ("TextWidgetClass", name, attrs + (extra or []), None)


def button(name, x, y, w, h, prio, kids, visible=1):
    # `style Empty`: a style-less button paints a light box (dayz-modding gui-layouts §31).
    attrs = [("visible", visible)] + exact(x, y, w, h) + [("text", '""'), ("priority", prio), ("style", "Empty")]
    return ("ButtonWidgetClass", name, attrs, kids)


def shape(name, x, y, w, h, r, color, prio=0, overlap=0.25, extra=None):
    """A box of one colour with round corners of `r` units: four quarter discs and three
    bands; the bands overlap the corners a little where nothing shows through."""
    if r <= 0:
        return panel(name, exact(x, y, w, h), color, prio, extra)
    o = overlap
    kids = [
        image(name + "TL", exact(0, 0, r, r), 0, "ozg_rc_tl_ca", color),
        image(name + "TR", exact(w - r, 0, r, r), 0, "ozg_rc_tr_ca", color),
        image(name + "BL", exact(0, h - r, r, r), 0, "ozg_rc_bl_ca", color),
        image(name + "BR", exact(w - r, h - r, r, r), 0, "ozg_rc_br_ca", color),
        panel(name + "M", exact(0, r - o, w, h - 2 * r + 2 * o), color, 0),
        panel(name + "T", exact(r - o, 0, w - 2 * r + 2 * o, r), color, 0),
        panel(name + "B", exact(r - o, h - r, w - 2 * r + 2 * o, r), color, 0),
    ]
    return frame(name, exact(x, y, w, h), prio, kids, extra)


def box(name, x, y, w, h, r, fill, ring=None, outside=False, prio=0, extra=None):
    """A rounded box with its ground `<name>Bg` and, given `ring`, a one-unit ring
    `<name>Edge` inside it (a CSS inset shadow or a border) or round it (`outside`)."""
    kids = []
    if ring and outside:
        kids.append(shape(name + "Edge", -1, -1, w + 2, h + 2, r + 1, rgb(ring), 0))
        kids.append(shape(name + "Bg", 0, 0, w, h, r, rgb(fill), 1))
    elif ring:
        kids.append(shape(name + "Edge", 0, 0, w, h, r, rgb(ring), 0))
        kids.append(shape(name + "Bg", 1, 1, w - 2, h - 2, max(0, r - 1), rgb(fill), 1))
    else:
        kids.append(shape(name + "Bg", 0, 0, w, h, r, rgb(fill), 0))
    return frame(name, exact(x, y, w, h), prio, kids, extra)


def btn(name, x, y, w, h, r, fill, ring, label, px, face, ink, prio=20, visible=1, label_w=None):
    """A button as the canvas draws it: its box, its words in the middle."""
    kids = [box(name + "Box", 0, 0, w, h, r, fill, ring, prio=0)]
    lw = label_w if label_w is not None else w
    kids.append(text(name + "Text", 0, 0, lw, h, px, face, ink, 3, "center", label))
    return button(name, x, y, w, h, prio, kids, visible)



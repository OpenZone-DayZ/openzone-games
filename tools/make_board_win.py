def quarter(corner, inverted=False, size=128, ss=4):
    """A quarter disc filling a corner (the centre at the box's inner corner), white,
    smoothed; inverted: white outside the arc (a mask over a picture's corner)."""
    n = size * ss
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    cx = n if corner[1] == "l" else 0
    cy = n if corner[0] == "t" else 0
    d.ellipse((cx - n, cy - n, cx + n, cy + n), fill=255)
    if inverted:
        img = img.point(lambda v: 255 - v)
    alpha = img.resize((size, size), LANCZOS)
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(alpha)
    return out


def disc(size=256, ss=4, ring=0.0):
    """A white disc; with `ring` (a part of the diameter) a ring of that width alone."""
    n = size * ss
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    d.ellipse((ss, ss, n - 1 - ss, n - 1 - ss), fill=255)
    if ring > 0:
        w = ring * n
        d.ellipse((ss + w, ss + w, n - 1 - ss - w, n - 1 - ss - w), fill=0)
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(img.resize((size, size), LANCZOS))
    return out


def check_glow(size=256):
    """The king in check: the canvas's radial-gradient(circle, red 85% -> clear at 72%) of
    a square -- 72% of the way to its farthest corner."""
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    px = out.load()
    c = size / 2.0
    reach = 0.72 * math.hypot(c, c)
    for y in range(size):
        for x in range(size):
            d = math.hypot(x + 0.5 - c, y + 0.5 - c)
            a = max(0.0, 1.0 - d / reach)
            px[x, y] = (255, 255, 255, int(round(255 * 0.85 * a)))
    return out


def board_shadow(size=512):
    """The board's soft shadow: 880 units of board in a picture of 1040, blurred 40."""
    k = size / 1040.0
    img = Image.new("L", (size, size), 0)
    d = ImageDraw.Draw(img)
    d.rectangle((80 * k, 80 * k, 960 * k, 960 * k), fill=255)
    img = img.filter(ImageFilter.GaussianBlur(20 * k))
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(img)
    return out


def stroke(points_list, grid, width, size=64, ss=4):
    """Lines of a small svg (the canvas's close cross, the menu's chevron), white."""
    n = size * ss
    k = n / grid
    img = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(img)
    w = max(1, int(round(width * k)))
    for pts in points_list:
        p = [(x * k, y * k) for x, y in pts]
        d.line(p, fill=255, width=w, joint="curve")
        for x, y in (p[0], p[-1]):
            r = w / 2.0
            d.ellipse((x - r, y - r, x + r, y + r), fill=255)
    out = Image.new("RGBA", (size, size), (255, 255, 255, 0))
    out.putalpha(img.resize((size, size), LANCZOS))
    return out


def save(img, stem, paa):
    os.makedirs(ART, exist_ok=True)
    png = os.path.join(ART, stem + ".png")
    img.save(png)
    line = "%s %dx%d" % (stem, img.size[0], img.size[1])
    if paa:
        os.makedirs(PAA_OUT, exist_ok=True)
        target = os.path.join(PAA_OUT, stem + ".paa")
        if os.path.exists(target):
            os.remove(target)
        done = subprocess.run([paa, png, target], capture_output=True, text=True, stdin=subprocess.DEVNULL)
        if done.returncode != 0 or not os.path.isfile(target):
            raise SystemExit("ImageToPAA failed for " + stem + ": " + done.stdout + done.stderr)
        line += "  -> %d KB" % (os.path.getsize(target) // 1024)
    print(line)



    save(check_glow(), "ozg_check_ca", paa)
    save(board_shadow(), "ozg_bshadow_ca", paa)
    save(stroke([[(2, 2), (10, 10)], [(10, 2), (2, 10)]], 12, 1.8), "ozg_icon_x_ca", paa)
    save(stroke([[(1, 3), (5, 7), (9, 3)]], 10, 1.6), "ozg_icon_chev_ca", paa)


